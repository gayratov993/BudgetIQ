export const dictionaries: Record<Locale, Dictionary> = { uz, ru, en };

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}

export function parseLocale(value: string | null | undefined): Locale {
  return isLocale(value) ? value : DEFAULT_LOCALE;
}

const CATEGORY_KEYS: Record<string, keyof Dictionary["categories"]> = {
  "cat-food": "food",
  "cat-transport": "transport",
  "cat-housing": "housing",
  "cat-utilities": "utilities",
  "cat-cafe": "cafe",
  "cat-entertainment": "entertainment",
  "cat-health": "health",
  "cat-clothes": "clothes",
  "cat-education": "education",
  "cat-other-expense": "otherExpense",
  "cat-salary": "salary",
  "cat-freelance": "freelance",
  "cat-investment": "investment",
  "cat-other-income": "otherIncome",
};

export function localizeCategoryName(id: string, fallback: string, d: Dictionary): string {
  const key = CATEGORY_KEYS[id];
  return key ? d.categories[key] : fallback;
}
